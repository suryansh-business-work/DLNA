/** Normalise a MAC into `AABBCCDDEEFF`. */
export function normalizeMac(mac: string): string {
  return mac.replace(/[^0-9a-fA-F]/g, '').toUpperCase();
}

/** Format a MAC as `AA:BB:CC:DD:EE:FF`, or return the input unchanged. */
export function formatMac(mac: string): string {
  const raw = normalizeMac(mac);
  if (raw.length !== 12) return mac;
  return raw.match(/.{2}/g)!.join(':');
}

/** `00:00:00:00:00:00` and broadcast are placeholders, not real hosts. */
export function isUsableMac(mac?: string): mac is string {
  if (!mac) return false;
  const raw = normalizeMac(mac);
  return raw.length === 12 && raw !== '000000000000' && raw !== 'FFFFFFFFFFFF';
}

/**
 * Locally-administered addresses have bit 1 of the first octet set. iOS 14+,
 * Android 10+ and Windows 10+ all use these as per-network "private" MACs, so
 * seeing one is itself a decent hint that the device is a phone, tablet or
 * laptop rather than a TV or a NAS.
 */
export function isRandomizedMac(mac: string): boolean {
  const raw = normalizeMac(mac);
  if (raw.length !== 12) return false;
  const firstOctet = parseInt(raw.slice(0, 2), 16);
  if (Number.isNaN(firstOctet)) return false;
  // Ignore multicast (bit 0) - those are not host addresses at all.
  return (firstOctet & 0x02) !== 0 && (firstOctet & 0x01) === 0;
}

export function lookupVendor(mac?: string): VendorMatch | undefined {
  if (!isUsableMac(mac)) return undefined;
  const raw = normalizeMac(mac);
  const randomized = isRandomizedMac(raw);
  const vendor = OUI.get(raw.slice(0, 6));

  if (vendor) return { vendor, randomized };
  if (randomized) return { vendor: 'Private Wi-Fi address', randomized: true };
  return undefined;
}

