/**
 * MAC address -> vendor lookup.
 *
 * The full IEEE registry is ~35k entries and several MB, which is overkill to
 * ship inside a desktop app. This is a curated subset covering the consumer
 * hardware you actually meet on a home Wi-Fi network: phones, TVs, streaming
 * sticks, speakers, consoles, routers and NAS boxes. Anything outside the table
 * resolves to `undefined`, which the classifier treats as "no vendor signal"
 * rather than as an error.
 */

export interface VendorMatch {
  vendor: string;
  /** True when the MAC is a locally-administered / randomised address. */
  randomized: boolean;
}

const OUI = new Map<string, string>();

/**
 * Registers a whitespace-separated list of 24-bit OUI prefixes for a vendor.
 * Tokens that are not exactly six hex digits are ignored so a typo in the
 * table degrades to a missing lookup instead of a bogus match.
 */
function register(vendor: string, prefixes: string): void {
  for (const token of prefixes.split(/\s+/)) {
    const prefix = token.toUpperCase();
    if (/^[0-9A-F]{6}$/.test(prefix) && !OUI.has(prefix)) {
      OUI.set(prefix, vendor);
    }
  }
}

